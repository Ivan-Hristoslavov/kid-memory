import { DELIVERY, formatPrice, lowestPriceEUR } from "@/lib/catalog";

/**
 * Gift-occasion articles. These target the searches that actually convert for a
 * personalised gift — "подарък за 1 юни", "подарък за баба" — which is the
 * cheapest traffic this shop can get.
 *
 * Content lives here rather than in a CMS because there will be a handful of
 * long-lived pages, not a publishing operation. Body is plain paragraphs and
 * headings so it renders identically on the page and reads well to a crawler.
 */
